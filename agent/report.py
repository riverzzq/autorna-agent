"""Per-run HTML report — AutoRNA Agent, Week 3 step 4.

One self-contained page per run: run status and wall time, the QC
table (per-sample percent_mapped, NumReads, gate pass/fail), the
DESeq2 summary when it exists (gene count, significant count, top
genes), excluded samples, and links to the MultiQC report and the
DESeq2 results.tsv. All numbers come from files already on disk
(qc.json, deseq2/summary.json); nothing is recomputed or invented
here. If a section has no data yet, the page says so plainly.
"""
import html
import json
from pathlib import Path


def _qc_rows(qc):
    rows = []
    for s in qc.get("samples", []):
        gates = s.get("gates", {})
        mapping = gates.get("mapping_rate", {})
        reads = gates.get("num_reads", {})
        pct = s.get("percent_mapped")
        num = s.get("num_reads")
        rows.append(
            "<tr><td>{sample}</td><td>{group}</td><td>{pct}</td><td>{num}</td>"
            "<td>{mapping}</td><td>{reads}</td><td>{verdict}</td></tr>".format(
                sample=html.escape(str(s.get("sample", ""))),
                group=html.escape(str(s.get("group", ""))),
                pct=f"{pct:.1f}%" if pct is not None else "missing",
                num=f"{num:,.0f}" if num is not None else "missing",
                mapping="pass" if mapping.get("pass") else "fail",
                reads="pass" if reads.get("pass") else "fail",
                verdict="PASS" if s.get("pass") else "FAIL",
            )
        )
    return "\n".join(rows)


def _deseq2_section(summary):
    if not summary:
        return "<p>DESeq2 has not run yet for this run. Use POST /jobs/{run_id}/deseq2.</p>"
    top_rows = "\n".join(
        "<tr><td>{gene}</td><td>{lfc}</td><td>{padj}</td></tr>".format(
            gene=html.escape(str(g.get("gene", ""))),
            lfc=f"{g['log2FoldChange']:.2f}" if g.get("log2FoldChange") is not None else "NA",
            padj=f"{g['padj']:.2e}" if g.get("padj") is not None else "NA",
        )
        for g in summary.get("top_genes", [])
    )
    excluded = summary.get("samples_excluded") or []
    excluded_note = (
        f"<p>Excluded by QC gates: {', '.join(html.escape(str(s)) for s in excluded)}.</p>"
        if excluded else "<p>No samples excluded by QC gates.</p>"
    )
    return (
        f"<p>{summary.get('n_genes', 0)} genes tested, "
        f"{summary.get('n_significant', 0)} significant "
        f"(padj &lt; 0.05 and |log2FC| &gt; 1). "
        f"tx2gene pairs: {summary.get('tx2gene_pairs', 'unknown')}.</p>"
        f"{excluded_note}"
        "<table><tr><th>Gene</th><th>log2FC</th><th>padj</th></tr>"
        f"{top_rows}</table>"
    )


def build_report(run_dir):
    """Write runs/<run_id>/report.html and return its path."""
    run_dir = Path(run_dir)
    run_id = run_dir.name
    qc_path = run_dir / "qc.json"
    qc = json.loads(qc_path.read_text()) if qc_path.exists() else None
    deseq2_path = run_dir / "deseq2" / "summary.json"
    deseq2 = json.loads(deseq2_path.read_text()) if deseq2_path.exists() else None

    qc_section = (
        f"<p>qc_pass = {qc.get('qc_pass')} (1 = all samples passed, 0 = at least one failed). "
        f"Failed samples: {', '.join(qc.get('failed_samples', [])) or 'none'}.</p>"
        "<table><tr><th>Sample</th><th>Group</th><th>% mapped</th><th>NumReads</th>"
        "<th>Mapping gate</th><th>Reads gate</th><th>Verdict</th></tr>"
        f"{_qc_rows(qc)}</table>"
        if qc else "<p>QC has not run yet for this run. Use GET /jobs/{run_id}/qc.</p>"
    )
    multiqc_link = (
        '<p><a href="results/multiqc/multiqc_report.html">MultiQC report</a> '
        '(opens the full interactive report).</p>'
        if (run_dir / "results" / "multiqc" / "multiqc_report.html").exists()
        else "<p>MultiQC report not found under results/multiqc/.</p>"
    )
    deseq2_link = (
        '<p><a href="deseq2/results.tsv">DESeq2 results.tsv</a> '
        '<a href="deseq2/volcano.pdf">volcano.pdf</a></p>'
        if (run_dir / "deseq2" / "results.tsv").exists() else ""
    )
    page = """<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<title>AutoRNA report — {run_id}</title>
<style>
body{{font-family:-apple-system,Helvetica,Arial,sans-serif;max-width:900px;margin:2em auto;padding:0 1em;color:#222}}
table{{border-collapse:collapse;margin:1em 0}} th,td{{border:1px solid #ccc;padding:4px 10px;text-align:left}}
th{{background:#f0f0f0}} h1{{font-size:1.4em}} h2{{font-size:1.15em;margin-top:1.5em}}
</style></head><body>
<h1>AutoRNA report — {run_id}</h1>
<p>Contrast: {contrast}</p>
<h2>QC gates</h2>
{qc_section}
{multiqc_link}
<h2>DESeq2</h2>
{deseq2_section}
{deseq2_link}
<p><small>Generated by AutoRNA Agent (agent/report.py). Numbers come from
runs/{run_id}/qc.json and runs/{run_id}/deseq2/summary.json; nothing here is
estimated or invented.</small></p>
</body></html>""".format(
        run_id=html.escape(run_id),
        contrast=html.escape(str((qc or {}).get("contrast") or (deseq2 or {}).get("contrast") or "unknown")),
        qc_section=qc_section,
        multiqc_link=multiqc_link,
        deseq2_section=_deseq2_section(deseq2),
        deseq2_link=deseq2_link,
    )
    out = run_dir / "report.html"
    out.write_text(page)
    return out
